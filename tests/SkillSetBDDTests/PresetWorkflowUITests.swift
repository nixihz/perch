import Foundation
import XCTest
import SkillSetCore

@MainActor
final class PresetWorkflowUITests: XCTestCase {
    func testEveryPresetCanBeEditedAndDuplicatedWithoutChangingOriginalOrProject() throws {
        guard NativeUIHarness.canRunInCurrentEnvironment else { throw XCTSkip(NativeUIHarness.unavailableReason) }
        let world = try BDDWorld()
        defer { world.cleanup() }
        try world.registerProject(named: "user-presets")
        try world.launchNativeUI()
        let ui = try XCTUnwrap(world.nativeUI)
        let store = PresetStore(rootURL: ui.applicationSupportRoot)
        try ui.selectSidebarItem("预设")
        try ui.waitForStaticText("预设")
        XCTAssertTrue(try ui.hasEnabledButton("预览"))
        XCTAssertTrue(try ui.hasEnabledButton("复制为新预设"))
        try ui.waitForButton("预览")
        try ui.setText(fieldMatching: "presets.editor.name", to: "我的日常工程")
        try ui.pressButton(identifier: "presets.editor.preview")
        try ui.waitForButton("保存")
        try ui.pressButton(identifier: "presets.review.save")
        try ui.waitForButton("用于项目…")
        let original = try XCTUnwrap(store.list().first)
        XCTAssertEqual(original.id, "personal-base")
        XCTAssertEqual(original.name, "我的日常工程")
        XCTAssertEqual(original.revision, 2)
        let before = try Data(contentsOf: store.documentURL)
        try ui.pressButton(identifier: "presets.duplicate")
        try ui.waitForStaticText("新建预设")
        XCTAssertFalse(try ui.buttonIsEnabled("预览"))
        try ui.pressButton("取消")
        try ui.waitForButton("用于项目…")
        XCTAssertEqual(try Data(contentsOf: store.documentURL), before)
        try ui.pressButton(identifier: "presets.duplicate")
        try ui.waitForStaticText("新建预设")
        try ui.setText(fieldMatching: "presets.editor.name", to: "日常工程副本")
        try ui.pressButton(identifier: "presets.editor.preview")
        try ui.waitForButton("保存")
        try ui.pressButton(identifier: "presets.review.save")
        try ui.waitForButton("用于项目…")
        let records = try store.list()
        let copy = try XCTUnwrap(records.first { $0.id != original.id })
        XCTAssertEqual(records.count, 2)
        XCTAssertEqual(records.first { $0.id == original.id }, original)
        XCTAssertEqual(copy.name, "日常工程副本")
        XCTAssertEqual(copy.revision, 1)
        XCTAssertEqual(copy.skills, original.skills)
        XCTAssertEqual(copy.instructionFragments, original.instructionFragments)
        XCTAssertTrue(try ui.hasEnabledButton("预览"))
        XCTAssertTrue(try ui.hasEnabledButton("复制为新预设"))
        let project = try XCTUnwrap(ProjectStore(rootURL: ui.applicationSupportRoot).list().first)
        XCTAssertEqual(try FileManager.default.contentsOfDirectory(atPath: project.canonicalPath), [])
        XCTAssertTrue(try ui.planRecords().isEmpty)
    }

    func testProjectAndPresetEntriesReviewCancelAndLoadWithoutWritingProjectFiles() throws {
        guard NativeUIHarness.canRunInCurrentEnvironment else { throw XCTSkip(NativeUIHarness.unavailableReason) }
        let world = try BDDWorld()
        defer { world.cleanup() }
        try world.registerProject(named: "preset-demo")
        world.selectSkill("local-brian/research")
        world.selectAgent("claude-code")
        try world.launchNativeUI()
        let ui = try XCTUnwrap(world.nativeUI)
        let registration = try XCTUnwrap(ProjectStore(rootURL: ui.applicationSupportRoot).list().first)
        let store = ProjectDraftStore(rootURL: ui.applicationSupportRoot)
        let before = try Data(contentsOf: store.documentURL)

        try ui.pressButton("使用预设…")
        try ui.waitForButton("载入项目草稿")
        XCTAssertTrue(try ui.hasStaticText("目标项目：preset-demo"))
        XCTAssertTrue(try ui.hasStaticText("与当前草稿比较"))
        try ui.focusButton(identifier: "presets.option.personal-base")
        try ui.pressDownArrow()
        try ui.waitForStaticText(containing: "有设计约定，有交互细节，也有真实验证。")
        try ui.pressButton(identifier: "presets.option.research-first")
        try ui.waitForStaticText(containing: "先核对原始资料，再记录依据与待定项。")
        XCTAssertEqual(try Data(contentsOf: store.documentURL), before, "切换预设只更新预览")
        try ui.pressEscapeToCancelPlan()
        XCTAssertEqual(try Data(contentsOf: store.documentURL), before, "Escape 不能覆盖草稿")

        try ui.selectSidebarItem("预设")
        try ui.waitForButton("用于项目…")
        try ui.pressButton("用于项目…")
        try ui.waitForButton("载入项目草稿")
        XCTAssertTrue(try ui.hasEnabledButton("添加本机目录…"))
        try ui.pressButton("取消")
        try ui.waitForButton("用于项目…")
        XCTAssertEqual(try Data(contentsOf: store.documentURL), before, "取消不能覆盖草稿")

        try ui.pressButton("用于项目…")
        try ui.waitForButton("载入项目草稿")
        try ui.pressButton("载入项目草稿")
        try ui.waitForButton("使用预设…")
        XCTAssertEqual(try ui.sidebarSelection().components(separatedBy: " | ").first, "项目")
        XCTAssertFalse(try ui.sheetPresent())
        let saved = try XCTUnwrap(store.load(projectID: registration.id))
        XCTAssertEqual(saved.skillIDs, ["workspace/brian-working-style", "workspace/project-guide", "workspace/stc"])
        XCTAssertEqual(saved.instructionIDs, ["base-zh", "engineering"])
        XCTAssertEqual(saved.agents, ["claude-code"])
        XCTAssertTrue(try ui.planRecords().isEmpty)
        XCTAssertEqual(try FileManager.default.contentsOfDirectory(atPath: registration.canonicalPath), [])
    }

    func testCreatePresetWithMCPAndAgentsRulesThenCancelEditingWithoutWritingProject() throws {
        guard NativeUIHarness.canRunInCurrentEnvironment else { throw XCTSkip(NativeUIHarness.unavailableReason) }
        let world = try BDDWorld()
        defer { world.cleanup() }
        try world.registerProject(named: "preset-authoring")
        try world.launchNativeUI()
        let ui = try XCTUnwrap(world.nativeUI)
        try ui.selectSidebarItem("预设")
        try ui.pressButton(identifier: "presets.new")
        try ui.waitForStaticText("新建预设")
        XCTAssertFalse(try ui.buttonIsEnabled("预览"))
        try ui.setText(fieldMatching: "presets.editor.name", to: "我的开发组合")
        try ui.selectRadioButton("AGENTS 片段")
        try ui.pressButton(identifier: "presets.editor.rule.engineering")
        try ui.selectRadioButton("MCP 服务")
        try ui.pressButton(identifier: "presets.editor.addMCP")
        try ui.waitForButton("保存连接")
        try ui.setText(fieldMatching: "presets.mcp.name", to: "docs")
        try ui.setText(fieldMatching: "presets.mcp.command", to: "/usr/bin/true")
        try ui.pressButton(identifier: "presets.mcp.save")
        try ui.waitForButton("预览")
        try ui.pressButton(identifier: "presets.editor.preview")
        try ui.waitForButton("保存")
        try ui.pressButton(identifier: "presets.review.save")
        try ui.waitForButton("用于项目…")
        let store = PresetStore(rootURL: ui.applicationSupportRoot)
        let saved = try XCTUnwrap(store.list().first)
        XCTAssertEqual(saved.name, "我的开发组合")
        XCTAssertEqual(saved.instructionFragments, ["engineering"])
        XCTAssertEqual(saved.mcpServers.first?.commandOrURL, "/usr/bin/true")
        let before = try Data(contentsOf: store.documentURL)
        try ui.waitForButton("预览")
        try ui.setText(fieldMatching: "presets.editor.name", to: "未保存的名称")
        try ui.pressButton("放弃修改")
        try ui.waitForConfirmationAlert()
        try ui.pressButton(identifier: "action-button-1")
        try ui.waitForButton("用于项目…")
        XCTAssertEqual(try Data(contentsOf: store.documentURL), before)
        let project = try XCTUnwrap(ProjectStore(rootURL: ui.applicationSupportRoot).list().first)
        XCTAssertEqual(try FileManager.default.contentsOfDirectory(atPath: project.canonicalPath), [])
        XCTAssertTrue(try ui.planRecords().isEmpty)
    }

